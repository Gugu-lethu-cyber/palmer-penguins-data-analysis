import pandas as pd
import matplotlib.pyplot as plt

url = "https://raw.githubusercontent.com/allisonhorst/palmerpenguins/main/inst/extdata/penguins.csv"

penguins = pd.read_csv(url)
penguins.head()

print ("Dataset shape:", penguins.shape)
print ("\nColumn names:")
print (penguins.columns)
penguins.info()

missing_values = penguins.isnull().sum()

print(missing_values)

missing_percentage = (penguins.isnull().sum() / len(penguins)) * 100

print(missing_percentage.round(2))

penguins.describe()

penguins["species"].value_counts()

penguins.groupby(["species", "sex"]).size()

penguins[penguins.isnull().any(axis=1)]

# Create a copy of the dataset

penguins_clean = penguins.dropna(
    subset=[
        "bill_length_mm",
        "bill_depth_mm",
        "flipper_length_mm",
        "body_mass_g"
    ]
)

print("Original dataset:", penguins.shape)
print("Cleaned dataset:", penguins_clean.shape)
# Check missing values after cleaning

penguins_clean.isnull().sum()

# Calculate average body mass for each species

average_mass = penguins_clean.groupby("species")["body_mass_g"].mean()

print(average_mass)

# Create a bar chart

average_mass.plot(
    kind="bar",
    title="Average Body Mass by Penguin Species",
    xlabel="Penguin Species",
    ylabel="Average Body Mass (g)"
)

plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

average_flipper = penguins_clean.groupby("species")["flipper_length_mm"].mean()

print(average_flipper)

average_flipper.plot(
    kind="bar",
    title="Average Flipper Length by Penguin Species",
    xlabel="Penguin Species",
    ylabel="Average Flipper Length (mm)"
)

plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

plt.figure(figsize=(8, 5))

plt.scatter(
    penguins_clean["flipper_length_mm"],
    penguins_clean["body_mass_g"]
)

plt.title("Flipper Length vs Body Mass")
plt.xlabel("Flipper Length (mm)")
plt.ylabel("Body Mass (g)")

plt.tight_layout()
plt.show()

correlation = penguins_clean["flipper_length_mm"].corr(
    penguins_clean["body_mass_g"]
)

print("Correlation:", round(correlation, 3))

